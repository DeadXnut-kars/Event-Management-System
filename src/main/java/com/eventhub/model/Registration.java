package com.eventhub.model;

import jakarta.persistence.*;
import jakarta.validation.constraints.Email;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Size;

import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;

// Entity mapped to 'registrations' table with a database composite unique constraint to enforce one registration per email per event
@Entity
@Table(name = "registrations", uniqueConstraints = {
    @UniqueConstraint(name = "uq_event_email", columnNames = {"event_id", "email"})
})
public class Registration {

    // Primary key identifier automatically generated by database
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    // Unique alphanumeric ticket / admission pass code issued to the registrant
    @Column(name = "registration_code", nullable = false, unique = true, length = 30)
    private String registrationCode;

    // Many-to-one foreign key relationship binding this attendee registration to a specific event
    @ManyToOne(fetch = FetchType.EAGER)
    @JoinColumn(name = "event_id", nullable = false)
    private Event event;

    // Attendee full legal or preferred name with mandatory presence check
    @NotBlank(message = "Name is required")
    @Size(min = 2, max = 100, message = "Name must be between 2 and 100 characters")
    @Column(name = "participant_name", nullable = false, length = 100)
    private String participantName;

    // Attendee email address validated by standard email syntax pattern
    @NotBlank(message = "Email is required")
    @Email(message = "Please enter a valid email address")
    @Column(nullable = false, length = 100)
    private String email;

    // Contact telephone number for emergency notifications or ticket verification
    @NotBlank(message = "Phone number is required")
    @Size(min = 7, max = 20, message = "Please enter a valid phone number")
    @Column(nullable = false, length = 20)
    private String phone;

    // Company, school, or organization affiliation of participant
    @Column(length = 100)
    private String organization;

    // Professional role, job designation, or student status
    @Column(length = 50)
    private String roleTitle;

    // Dietary preferences, accessibility accommodations, or custom requirements
    @Column(name = "special_notes", columnDefinition = "TEXT")
    private String specialNotes;

    // Immutable timestamp recording exact moment registration was submitted
    @Column(name = "registration_date", updatable = false)
    private LocalDateTime registrationDate = LocalDateTime.now();

    public Registration() {
    }

    public Registration(String registrationCode, Event event, String participantName, 
                        String email, String phone, String organization, String roleTitle, 
                        String specialNotes) {
        this.registrationCode = registrationCode;
        this.event = event;
        this.participantName = participantName;
        this.email = email;
        this.phone = phone;
        this.organization = organization;
        this.roleTitle = roleTitle;
        this.specialNotes = specialNotes;
        this.registrationDate = LocalDateTime.now();
    }

    public String getFormattedDate() {
        if (registrationDate == null) return "N/A";
        DateTimeFormatter formatter = DateTimeFormatter.ofPattern("dd MMM yyyy, hh:mm a");
        return registrationDate.format(formatter);
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getRegistrationCode() {
        return registrationCode;
    }

    public void setRegistrationCode(String registrationCode) {
        this.registrationCode = registrationCode;
    }

    public Event getEvent() {
        return event;
    }

    public void setEvent(Event event) {
        this.event = event;
    }

    public String getParticipantName() {
        return participantName;
    }

    public void setParticipantName(String participantName) {
        this.participantName = participantName;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getPhone() {
        return phone;
    }

    public void setPhone(String phone) {
        this.phone = phone;
    }

    public String getOrganization() {
        return organization;
    }

    public void setOrganization(String organization) {
        this.organization = organization;
    }

    public String getRoleTitle() {
        return roleTitle;
    }

    public void setRoleTitle(String roleTitle) {
        this.roleTitle = roleTitle;
    }

    public String getSpecialNotes() {
        return specialNotes;
    }

    public void setSpecialNotes(String specialNotes) {
        this.specialNotes = specialNotes;
    }

    public LocalDateTime getRegistrationDate() {
        return registrationDate;
    }

    public void setRegistrationDate(LocalDateTime registrationDate) {
        this.registrationDate = registrationDate;
    }
}
